CREATE TABLE gb_channel_video_share (
  id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  channel_pk NUMBER(19) NOT NULL UNIQUE,
  public_id VARCHAR(64) NOT NULL UNIQUE,
  generation VARCHAR(64) NOT NULL,
  enabled NUMBER(1) DEFAULT 0 NOT NULL,
  activated_at TIMESTAMP NULL,
  expires_at TIMESTAMP NULL,
  created_by NUMBER(19) NULL,
  device_pk NUMBER(19) NOT NULL,
  device_id VARCHAR(20) NOT NULL,
  device_epoch NUMBER(19) DEFAULT 0 NOT NULL,
  source VARCHAR(16) NOT NULL,
  policy_actor_id NUMBER(19) NULL,
  policy_revision NUMBER(19) DEFAULT 0 NOT NULL,
  key_id VARCHAR(64) NOT NULL,
  revision NUMBER(19) DEFAULT 1 NOT NULL,
  revoked_at TIMESTAMP NULL,
  revoke_reason VARCHAR(64) DEFAULT '' NOT NULL,
  created_at TIMESTAMP NOT NULL,
  updated_at TIMESTAMP NOT NULL
);
CREATE INDEX idx_video_share_enabled_expiry ON gb_channel_video_share (enabled, expires_at);
CREATE INDEX idx_video_share_created_by ON gb_channel_video_share (created_by);
CREATE INDEX idx_video_share_device_pk ON gb_channel_video_share (device_pk);
CREATE TABLE gb_device_video_share_policy (
  id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  device_pk NUMBER(19) NOT NULL UNIQUE,
  default_enabled NUMBER(1) DEFAULT 0 NOT NULL,
  source VARCHAR(16) NOT NULL,
  policy_actor_id NUMBER(19) NULL,
  policy_revision NUMBER(19) DEFAULT 0 NOT NULL,
  initialized_at TIMESTAMP NOT NULL,
  created_at TIMESTAMP NOT NULL,
  updated_at TIMESTAMP NOT NULL
);

CREATE TABLE gb_video_share_authority (id NUMBER(19) NOT NULL PRIMARY KEY, revision NUMBER(19) DEFAULT 0 NOT NULL);
