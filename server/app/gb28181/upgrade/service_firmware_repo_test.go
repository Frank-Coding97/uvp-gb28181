// TC6.3: validateRequest 条件校验
func TestValidateRequest_ConditionalChecks(t *testing.T) {
	tests := []struct {
		name      string
		request   Request
		wantError bool
		errorMsg  string
	}{
		{
			name: "固件仓库模式：FirmwareID 非空，跳过 URL 格式校验",
			request: Request{
				Confirmed:  true,
				FirmwareID: "fw-123",
				FileURL:    "", // 空 URL，但固件仓库模式不校验
			},
			wantError: false,
		},
		{
			name: "手填模式：FileURL 为空报错",
			request: Request{
				Confirmed:    true,
				FirmwareID:   "",
				Firmware:     "V5.9.0",
				Manufacturer: "海康",
				FileURL:      "",
			},
			wantError: true,
			errorMsg:  "FileURL",
		},
		{
			name: "手填模式：Firmware 为空报错",
			request: Request{
				Confirmed:  true,
				FileURL:    "http://example.com/fw.bin",
				Firmware:   "",
			},
			wantError: true,
			errorMsg:  "Firmware",
		},
		{
			name: "手填模式：Manufacturer 为空报错",
			request: Request{
				Confirmed:    true,
				FileURL:      "http://example.com/fw.bin",
				Firmware:     "V5.9.0",
				Manufacturer: "",
			},
			wantError: true,
			errorMsg:  "Manufacturer",
		},
		{
			name: "手填模式：完整参数通过校验",
			request: Request{
				Confirmed:    true,
				FileURL:      "http://example.com/fw.bin",
				Firmware:     "V5.9.0",
				Manufacturer: "海康",
			},
			wantError: false,
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			target := Target{
				DeviceID:   1,
				DeviceCode: "34020000001320000001",
				Profile:    protocol.Profile{Version: protocol.Version2022},
			}

			err := validateRequest(target, tt.request)
			if tt.wantError {
				require.Error(t, err)
				assert.Contains(t, err.Error(), tt.errorMsg)
			} else {
				assert.NoError(t, err)
			}
		})
	}
}

