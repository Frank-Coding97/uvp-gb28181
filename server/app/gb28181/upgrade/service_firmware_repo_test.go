// TC6.1: 固件仓库模式 - FileURL 自动生成
func TestFirmwareRepositoryMode_FileURLAutoGenerated(t *testing.T) {
	// 不启动完整的 service，只测试 validateRequest 的条件分支
	t.Run("validateRequest allows empty FileURL when FirmwareID is provided", func(t *testing.T) {
		request := Request{
			Confirmed:  true,
			FirmwareID: "firmware-123",
			// FileURL, Firmware, Manufacturer 全部为空（由后续注入逻辑填充）
		}
		target := Target{
			DeviceID:   1,
			DeviceCode: "34020000001320000001",
			Profile:    protocol.Profile{Version: protocol.Version2022},
		}

		err := validateRequest(target, request)
		assert.NoError(t, err, "固件仓库模式应跳过 FileURL 校验")
	})

	t.Run("validateRequest requires FileURL when FirmwareID is empty", func(t *testing.T) {
		request := Request{
			Confirmed:    true,
			Firmware:     "V5.9.0",      // 提供 Firmware
			Manufacturer: "海康",         // 提供 Manufacturer
			FileURL:      "",            // 空 URL 应该报错
			// FirmwareID 为空，进入手填模式
		}
		target := Target{
			DeviceID:   1,
			DeviceCode: "34020000001320000001",
			Profile:    protocol.Profile{Version: protocol.Version2022},
		}

		err := validateRequest(target, request)
		assert.Error(t, err, "手填模式必须提供 FileURL")
		assert.Contains(t, err.Error(), "FileURL")
	})
}

