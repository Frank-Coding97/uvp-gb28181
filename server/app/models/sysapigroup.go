package models

// API 分组的受控清单（单一真源）。
//
// 为什么要有这份清单：sys_api.api_group 过去是**自由文本**（前端 a-input，后端只校验非空），
// 加上 scripts/button-catalog.py 每生成一批按钮就写死一个兜底分组，导致开发库里漂出
// 39 个分组：同模块被拆成兄弟组（云端录像拆 4 个）、前缀不统一（`GB28181设备管理` 缺空格）、
// 甚至出现 UTF-8 被二次编码的乱码组名。分组本身不参与鉴权（casbin 不读它），
// 但它是「接口管理」页唯一的可读组织维度，漂移后这张表就没法看了。
//
// 口径（与 docs/api-group-normalization.md 一致）：
//   - 分组名 = 该接口所属的**功能模块**，判定键是**接口自己的路径**（后端声明的模块归属），
//     由 scripts/api_groups.py 的 API_GROUP_RULES 维护、最长前缀匹配；
//   - 目录型顶层菜单（流媒体管理 / 日志中心）下的页面归到目录名；
//   - 隐藏路由页（设备录像回放）并入其入口页（多屏播放）。
//
// ⛔⛔ 判定键别改回「按钮所在页面」：播放控制台是工作台页面，云台/对讲/抓拍/配置下发/
// 视频参数/目标跟踪的按钮全摆在它上面，按页面推会把整片通道级设备操作算进「多屏播放」
// （2026-09-21 实测漂了 34 个接口）。同理，通道级操作单独成组「设备控制」，
// 不再混进「多屏播放」或「设备管理」。
//
// 顺序即前端下拉的展示顺序：业务模块在前，平台模块在后。
