// SysApiGroupNames 返回全部受控分组名。返回副本，调用方改不到内部清单。
func SysApiGroupNames() []string {
	out := make([]string, len(sysApiGroups))
	copy(out, sysApiGroups)
	return out
}

// IsValidSysApiGroup 判断分组名是否属于受控清单。
// 用于新增/编辑接口的写入校验：拒绝清单外的值，不再允许自由文本写入。
func IsValidSysApiGroup(name string) bool {
	for _, g := range sysApiGroups {
		if g == name {
			return true
		}
	}
	return false
}
